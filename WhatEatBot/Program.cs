async Task UpdateHandler(
    ITelegramBotClient bot,
    Update update,
    CancellationToken cancellationToken)
{
    if (update.Message is not { } message)
        return;

    if (message.Text is not { } text)
        return;

    if (text == "/start")
    {
        var keyboard = new ReplyKeyboardMarkup(new[]
        {
            new KeyboardButton[] { "🥤 Напитки", "🍲 Первые блюда" },
            new KeyboardButton[] { "🍗 Вторые блюда", "🥗 Салаты" }
        })
        {
            ResizeKeyboard = true
        };

        await bot.SendMessage(
            message.Chat.Id,
            "Привет! 👋\n\nЯ бот «Что поесть?» 🍽️\nВыбери категорию:",
            replyMarkup: keyboard,
            cancellationToken: cancellationToken
        );
    }
    else
    {
        string category = text switch
        {
            "🥤 Напитки" => "Напитки",
            "🍲 Первые блюда" => "Первые блюда",
            "🍗 Вторые блюда" => "Вторые блюда",
            "🥗 Салаты" => "Салаты",
            _ => ""
        };

        if (category != "")
        {
            await SendDish(
                bot,
                message.Chat.Id,
                message.From!.Id,
                category,
                cancellationToken
            );
        }
        else
        {
        }
    }
}

